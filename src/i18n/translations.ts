export type TranslationKey = keyof typeof FULL_PT_BR;

export const TRANSLATIONS: Record<AppLocale, Partial<Dictionary>> = {
  'pt-BR': FULL_PT_BR,
  'pt-PT': ptPT,
  en: FULL_EN,
  'en-GB': enGB,
  es: FULL_ES,
  de: FULL_DE,
  fr: FULL_FR,
  it: FULL_IT,
  zh: FULL_ZH,
  ja: FULL_JA,
  hi: FULL_HI,
};

const resolvedCache = new Map<AppLocale, Dictionary>();

function getResolvedDictionary(locale: AppLocale): Dictionary {
  const cached = resolvedCache.get(locale);
  if (cached) return cached;

  const merged = {} as Dictionary;
  for (const loc of getLocaleChain(locale)) {
    Object.assign(merged, TRANSLATIONS[loc]);
  }
  const fallbackLocale: AppLocale = locale.startsWith('pt') ? 'pt-BR' : 'en';
  for (const [key, value] of Object.entries(TRANSLATIONS[fallbackLocale])) {
    if (!(key in merged) && value != null) merged[key] = value;
  }
  resolvedCache.set(locale, merged);
  return merged;
}

export function translate(locale: AppLocale, key: TranslationKey, params?: Record<string, string | number>): string {
  let text = getResolvedDictionary(locale)[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(`{${k}}`, String(v));
    }
  }
  return text;
}
